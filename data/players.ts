import type { ID, Player, Position } from "@/types";

/** Rôle dans la rotation (utilisé par le simulateur pour répartir minutes et tirs). */
export type PlayerRole = "star" | "starter" | "rotation" | "bench";

/** Cibles statistiques d'un joueur (moyennes visées par le simulateur). */
export interface PlayerProfile {
  role: PlayerRole;
  ppg: number;
  rpg: number;
  apg: number;
  mpg: number;
  /** Part des tirs pris à 3 points (0 → 1). */
  threeRate: number;
}

export interface PlayerSeed extends Player {
  profile: PlayerProfile;
}

function roleFor(mpg: number, ppg: number, isNba: boolean): PlayerRole {
  const scale = isNba ? 1 : 0.72;
  if (ppg >= 20 * scale) return "star";
  if (mpg >= 26 * scale) return "starter";
  if (mpg >= 14 * scale) return "rotation";
  return "bench";
}

