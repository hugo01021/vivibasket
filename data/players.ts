function slug(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Joueur saisi à la main.
 * @param teamId club
 * @param birth  "YYYY-MM-DD"
 * @param nat    code pays ISO-3
 * @param ppg/rpg/apg/mpg moyennes visées, three = part des tirs à 3 pts
 */
function p(
  teamId: ID,
  firstName: string,
  lastName: string,
  jerseyNumber: number,
  position: Position,
  heightCm: number,
  weightKg: number,
  birth: string,
  nat: string,
  ppg: number,
  rpg: number,
  apg: number,
  mpg: number,
  three: number,
): PlayerSeed {
  const isNba = NBA_TEAMS.has(teamId);
  return {
    id: slug(`${firstName} ${lastName}`),
    firstName,
    lastName,
    teamId,
    jerseyNumber,
    position,
    heightCm,
    weightKg,
    birthDate: birth,
    nationality: nat,
    international: true,
    isFeatured: true,
    profile: { role: roleFor(mpg, ppg, isNba), ppg, rpg, apg, mpg, threeRate: three },
  };
}

